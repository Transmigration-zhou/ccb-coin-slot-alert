# 城市 → {区县名: 代码}；城市全称在各省之间不重名（见 tests/test_regions.py）
REGIONS: Dict[str, Dict[str, str]] = {
    city: districts for cities_ in PROVINCES.values() for city, districts in cities_.items()
}


class UnknownRegionError(ValueError):
    """城市或区县不在 REGIONS 中。"""


def cities() -> List[str]:
    return list(REGIONS)


def cities_by_province() -> Dict[str, List[str]]:
    return {prov: list(cs) for prov, cs in PROVINCES.items()}


def canonical_city(city: str) -> str:
    """把用户写的城市名解析成 REGIONS 中的全称：先精确匹配，再试加"市"，最后按唯一前缀匹配。"""
    city = city.strip()
    if city in REGIONS:
        return city
    if city + "市" in REGIONS:
        return city + "市"
    matches = [c for c in REGIONS if city and c.startswith(city)]
    if len(matches) == 1:
        return matches[0]
    if len(matches) > 1:
        raise UnknownRegionError(f"城市「{city}」有多个匹配：{'、'.join(matches)}，请写全称")
    raise UnknownRegionError(
        f"不支持的城市「{city}」；运行 python main.py list 查看支持的城市")


def districts_of(city: str) -> List[Tuple[str, str]]:
    """返回某城市的 [(区县名, 代码)]，顺序与 REGIONS 中一致。"""
    return list(REGIONS[canonical_city(city)].items())


def resolve_district(city: str, key: str) -> Tuple[str, str]:
    """按区县名称或代码查找，返回 (名称, 代码)。"""
    pairs = districts_of(city)
    for name, code in pairs:
        if key in (name, code):
            return name, code
    raise UnknownRegionError(
        f"「{city}」没有区县「{key}」，可选：{'、'.join(n for n, _ in pairs)}")
